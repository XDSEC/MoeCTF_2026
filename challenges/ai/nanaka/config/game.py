def compute_user_flag(team_id) -> str:
    """根据队伍ID动态计算flag，不依赖session存储明文flag。

    team_id 为队伍在 CTF 平台的整型 id（int 或可转 int 的 str）。
    用 FLAG_KEY 做 XXTEA 加密后，把加密值以 leet 替换隐藏进 FLAG_TEMPLATE，
    生成每队伍唯一的 moectf flag；同一密钥下可用 LeetStego.decode 校验回队号。
    """
    gen = LeetStego(FLAG_KEY)
    flag_hash = gen.encode(FLAG_TEMPLATE, int(team_id))
    return f"moectf{{{flag_hash}}}"


